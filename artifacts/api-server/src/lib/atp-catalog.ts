// are merely *retained* year to year (Circular S33 of 2022, reiterated by S15
// of 2024, then S19 of 2025); only the subjects named in an exclusion carry a
// newer plan. This catalog holds exactly those replaced plans, so the great
// majority of Slate presets keep their CAPS-derived sequence.
//
// `documentYear` is the vintage printed on the source document and
// `effectiveYear` is the teaching year the plan governs. They differ: the 2026
// CAT/IT plans run on 2023/24 documents.

